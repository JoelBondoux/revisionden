/**
 * Full looks (J15s, owner direction 2026-11-26): each effect style restyles the WHOLE app, not just
 * its accents. A look is a set of the shared design tokens (page, surfaces, edges, text, the main
 * colour, progress track, map hex fills, corners, shadows, heading font and the background
 * pattern's ink), in light and dark. Every shared component already reads these tokens, so cards,
 * buttons, button tiles, chips, the bottom nav, the map and progress bars all follow the style.
 *
 * Cue colours (right, wrong, warning, gold, streak) are never part of a look, so the colour-blind
 * palette keeps working in every style. Each style's stylesheet mirrors its look (a test keeps them
 * in step) and the contrast of every text pair is checked in light, dark and colour-blind.
 */
