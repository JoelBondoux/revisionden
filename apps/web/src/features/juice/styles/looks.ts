/** The CSS block for one look in one mode, as the style's stylesheet carries it. */
export function lookCss(id: EffectStyleId, mode: 'light' | 'dark'): string {
  const selector =
    mode === 'light'
      ? `:root[data-effect-style='${id}']:not([data-theme='dark'])`
      : `:root[data-effect-style='${id}'][data-theme='dark']`;
  const body = LOOK_TOKENS.map((t) => `  ${t}: ${LOOKS[id][mode][t]};`).join('\n');
  return `${selector} {\n${body}\n}`;
}
